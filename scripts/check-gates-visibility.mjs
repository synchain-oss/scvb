// check-gates-visibility.mjs —— 「浏览器在但没连上 ⇒ 必须显形」的**整条链**接线门禁
// (零依赖,Node >= 18,ESM)。
//
// [SL-297] 病灶:页面级冒烟在 CDP 握手失败时退 **2**,而 gates 3e 与 CI 都把 2 读成
//   「缺可选外部依赖」⇒ `[SKIP]` ⇒ **照算 PASS**。于是在一台**装着 Chrome** 的机器上,
//   一次瞬时超时就让整套判据**无声消失**,汇总行还写着全 PASS(SL-293 多轮 gates 撞到三次,
//   每次掉的套件还不一样,两套单独重跑都全绿 —— 丢的是运行机会,不是代码)。
//   修法是把它拆成 rc=3 + `[FLAKY-SKIP]`;而**那个修复自己也需要有人守着**。
//
// ⚠ 这条链有**三段**,少守一段就等于没守(复审【重要】点出第一版只守了第 ② 段);
//   ② 段里另挂了一族**同构**的接线:gate 3i 的标记 —— [SL-315] 起是 ALLOW 放行、
//   [SL-318] 起并上 WARN 降级。同一个失效方向(打了标记只在滚屏闪一行、汇总表照写
//   干净的 PASS),所以判据也同构 —— 三条「计数进标签」的断言共用**一个形态**
//   (`$<标签>` `=` … `$<计数>` `\b`,写法与理由都在 ② 段那条断言旁边)。
//   那一族**连同守着它的那道散文守卫**单列在下面 §④。
//   ① **生产端**:六套 `smoke-*-page.mjs` 的两个「有依赖但失败」出口必须走 `browserFailed()`。
//      它是**六份手抄副本** —— 「只改五份」「照旧模板新起一套」都是本仓有前科的形态;
//      把任一份改回 `noBrowser(`,那一套就静默退回 `[SKIP]` ⇒ 照算 PASS,病灶原样复现。
//   ② **gates 端**:`gates.ps1` 3e 的 rc=3 分支要有**独立计数**且**计数拼进汇总标签**。
//      只断「文件里有 FLAKY-SKIP 字样」是没牙的:那行 `Write-Host` 留着、计数没进
//      `$smokeLabel`,**恰恰就是本卡要防的形态**(标记只在滚屏里闪一下,汇总照写全 PASS)。
//   ③ **CI 端**:`format.yml` 的 rc=3 分支要在、且**不判红**。这一段的失效方向与 ② 相反:
//      删了它 flake 会落进 `[ $rc -ne 0 ]` ⇒ `::error::` + fail=1 ⇒ 在 required check 上
//      把瞬时抖动变成**硬红**,与本卡「不判红」的决定相反。那个方向是**响的**(CI 立刻红),
//      不像 ② 是**哑的**;但既然一并守得住,就不留这个不对称给后人猜。
//
// §④ **gate 3i 标记族的散文守卫**(挂在 ② 段里,判据与边界都以本节为准):
//   gate 3i 把这一圈脚本的成功输出按标记回显 ALLOW / BASE,又按行首标记把 WARN 数进
//   汇总标签。于是一句**带方括号**的散文(「见 [ 标记 ] 行」)就能冒充一条真信号 ——
//   轻则回显多一行,重则(散文恰好落在行首那一档)汇总表当场多报一档降级。
//   这条不变量在只有散文守着的时候被违反了**三次**(哪三次写在判据旁边,不在这里重复一遍 ——
//   同一份事实抄两处,改一处就是下一条假注释),所以给它一个跨文件的执行者。
//   · **执行面**从 `gates.ps1` gate 3i 的 `foreach` 里读,不手抄(读空了硬失败);
//   · **判据(第 ④ 版)**:在剥掉整行注释的**整份源码**上逐个找方括号标记,往回跳过空白,
//     **前一个字符是引号才算真信号**,其余判红。既不切字符串,也不看 `console.log` 的实参。
//   · **允许的引号只有 `"` 与 `'`**([SL-318] 去掉了反引号):markdown 反引号正是本仓散文
//     引用一个标记的惯例,留着它等于给整类散文盖章。反向代价为零 —— 今天七个脚本里的
//     真信号**全部**是双引号起头。**这里不写「几处」**:那个数在本卡自己手里就漂了两次
//     (夹具从字面量改成拼装,它自己就从命中面里消失了),而论证根本不依赖它 ——
//     同一条纪律 gates.ps1 gate 3i 的注释里已经写着「这里故意不写行号」。
//   · 前三版怎么错的(**四版是同一个洞逐层下降**,写在这里是为了别有人退回去):
//       ① 只扫 `console.log(...)` 的实参 ⇒ 被违反的那句提成了 `OK_MSG` 常量,注入实测照样绿;
//       ② 只扫双引号 ⇒ `check-native-paths` 的成功行本来就是模板串,旁边补一句就漏;
//       ③ 先用正则把「字符串字面量」切出来再扫 ⇒ 三种引号互相嵌套时**错配**,报到一段横跨
//          代码的假字面量上,**假红**;
//       ④ 改成「往回看一眼引号」⇒ 不再依赖 tokenize,但**允许集**成了新的判据面(见上一条)。
//   · **这道守卫挡不住的那一格(方向与上面相反,是漏判)**:它只看「标记前一个字符是不是引号」,
//     所以 `log(prefix + "  [WARN] …")` 会被**放行** —— 标记确实紧跟 `"`,但**实际输出行不以标记
//     起头**。gate 3i 的计数从 [SL-318] 起锚在行首,于是这一行**既不回显也不计数**,
//     静默漏一档降级(收紧回显那一半带来的新方向:旧写法至少还会回显一行)。
//     所以对生产者是一条**硬要求**:标记必须**开输出行**,别在它前面拼任何前缀。
//     散文版见 `check-bridge-parity.mjs` 那句「想加警告一律走 `warn()` helper」。
//   · **已知边界**:拼装写法(`"[" + "ALLOW] 行"`)天然不命中 —— 源码里根本没有连着的标记。
//     这是**夹具**的写法:本文件的反例夹具必须逐字带上那个标记,只能这么绕。
//     普通散文不必这么写,**去掉方括号**就行(报错话术给的也是这一条);
//     行内尾注释没剥(与下面那张表同一口径),注释里带方括号标记**会判红** —— 这一档偏严,
//     方向是假红不是漏判,回来读这一节就知道该怎么改。
//
// ⚠ 边界(照实说,别让人以为它更严):本检查是**文本级**的,不解析 PowerShell / YAML / JS。
//   · PowerShell 侧**先剥掉整行注释**再匹配 —— 否则一行 `# TODO: $smokeLabel 拼上 $smokeFlaky`
//     就能顶替真接线(复审指出的**漏判**口子,不是假红口子,已堵);
//   · ③ 段的 YAML/bash 侧**同样先剥整行注释**(与 ② 段对称,复审指出的漏判口子已堵);
//   · ① 段的 JS 侧**同样先剥整行注释**,且连块注释(`/*` ` * ` `*/`)一起收 ——
//     六套里 JSDoc 是常规写法,只剥 `//` 会让同一个哑弹换个注释符号回来;
//     **判定一律用剥过的那份**,连「是不是页面级冒烟」的执行面判据也是;
//   · §④ 的脚本扫描**同样先剥整行注释**(`//` 与块注释三形态)—— 与 ① 段共用
//     `stripJsComments`,[SL-318] 把此前两份逐字相同的拷贝合成了一份;
//   · **四处的行内尾注释都没剥**(`$x = 1  # …` / `foo(); // …`)—— ①②③ 三段里那一档同样
//     可被顶替,§④ 那一处方向相反(尾注释里写标记会**判红**,是偏严不是漏判)。
//     要堵得上 AST,对一道防「照模板复制」的门禁不划算;写在这里是为了别让人高估它;
//   · 变量改名 / 标签改用别的拼接写法(`-join`)会**假红**。假红逼人回来读这段注释,
//     漏判才会让洞悄悄回来 —— 所以这两类的方向是**不对称的**,别笼统说「方向安全」。
//   · 它**不验证运行时真打出了那行**;那由 SL-297 的删除式实跑覆盖(注入 CDP 握手失败 ⇒
//     汇总必须出现计数)。本检查只保证**接线还在**。
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const errors = [];
const fail = (m) => errors.push(m);
const read = (p) => fs.readFileSync(p, "utf8");

// PowerShell 注释:**块注释 `<# … #>` 整段剥掉**,再剥行首(允许缩进)是 `#` 的整行注释。
// [SL-322 复审第 5 轮] 块注释那一半原来漏着,而它比行注释更危险:`gates.ps1:1-27` 的
// `.SYNOPSIS` / `.DESCRIPTION` 帮助块里,`<#` 那行以 `<` 起头、body 各行以 `.` 或空格起头,
// **一行都不匹配 `/^\s*#/`**(只有收尾的 `#>` 被剥),于是整段原样留在 `ps` 里 —— 而且
// **每一行都在行首**,上一轮刚加的行首锚对它无效。把一条赋值抄进帮助块就能顶替真接线。
// 这一半修在**共用的过滤器**上,本文件 PowerShell 侧的每一条断言一起受益,不只是标签那三条。
const stripPsComments = (text) =>
    text
        .replace(/<#[\s\S]*?#>/g, "")
        .split("\n")
        .filter((l) => !/^\s*#/.test(l))
        .join("\n");

// JS 整行注释:`//` **与**块注释的三种行形态(`/*` 开头、` * ` 中间、`*/` 收尾)。
// ① 段与 §④ 用的是**同一份**过滤器 —— 此前是两份逐字相同的拷贝([SL-318] 合一),
// 两份拷贝的坏处不是重复,是**只改一份**:那正是本文件 ① 段自己写的「六份手抄副本」那一族。
const stripJsComments = (text) =>
    text
        .split("\n")
        .filter((l) => !/^\s*(\/\/|\/?\*)/.test(l))
        .join("\n");

// ---------------------------------------------------------------- ① 生产端
// 执行面按 **glob** 收,与 gate 3e / CI 同口径(`smoke-*.mjs`)——
// 加一套新的页面级冒烟会被自动守住,不必回来改这里。
// 「是页面级冒烟」的判据 = 它自己起浏览器(有 `chrome.on("error"`),
// 而不是靠文件名里有没有 `-page`:后者是命名约定,前者是事实。
const TESTS = path.join(ROOT, "web-preview", "tests");
const pageSuites = fs.existsSync(TESTS)
    ? fs
          .readdirSync(TESTS)
          .filter((f) => f.startsWith("smoke-") && f.endsWith(".mjs"))
          .map((f) => {
              const text = read(path.join(TESTS, f));
              // [SL-297 复审] **判定要用剥掉整行注释的那一份**。第一版直接在原文上
              // `includes("browserFailed")`,而我自己在 `smoke-monitor-page.mjs` 的
              // `if (!targets)` 上方写了一大段解释、里面就有 `browserFailed()` 字样 ——
              // 于是那条断言在**最该守的那个文件**上变成了哑弹:把真调用改回
              // `noBrowser(` 它照样绿。这是本卡第三次撞上同一形态(② PowerShell、
              // ③ YAML、这里 JS),三处口径统一:**整行注释一律先剥**。
              // 只剥**整行**注释,不碰行内 `//` —— 后者会把 `http://127.0.0.1` 这类串
              // 拦腰截断(`check-smoke-hygiene` 对同一个坑有明说)。
              // 块注释的三种行形态也一并收:六套里 JSDoc 是常规写法
              // (`smoke-monitor-page.mjs` 一个文件 5 处),只剥 `//` 的话,下一个人在
              // `if (!targets)` 附近补一句 `/** …走 browserFailed()… */`,
              // ① 段就**原样退回哑弹**,只是注释符号换了(复审指出)。
              const code = stripJsComments(text);
              return { name: f, code };
          })
          // 用剥过注释的 `code` 判定「是不是页面级冒烟」:注释里提一句 `chrome.on("error")`
          // 不应该把一个文件收进执行面。
          .filter((f) => f.code.includes('chrome.on("error"'))
    : [];

if (pageSuites.length === 0)
    fail(
        "web-preview/tests 下没找到任何起浏览器的 smoke-*.mjs —— 执行面收空了," +
            "本检查会退化成永远通过(参照 sccache「静默零命中照样绿」那一族)。",
    );

for (const s of pageSuites) {
    if (!/function\s+browserFailed\s*\(/.test(s.code))
        fail(
            `${s.name}:没有 browserFailed() —— 「浏览器在但没起来」会退回缺依赖那一档`,
        );
    // ★ 断的是**退出码**,不是名字。名字留着而 `process.exit(3)` 被改回 2,
    //   上面那条与 ②③ 两段**全绿**,而那一套的 CDP 超时又回到 `[SKIP]` ⇒ 照算 PASS ——
    //   两类当场合并,病灶原样复现,读代码的人却因为 `browserFailed` 这个名字还在而更确信。
    //   这正是本文件 ② 段自己写过的那句「只断『文件里有这个字样』是**没牙的**」。
    if (
        !/function\s+browserFailed\s*\([\s\S]{0,900}?process\.exit\(3\)/.test(
            s.code,
        )
    )
        fail(
            `${s.name}:browserFailed() 退的不是 3(或函数体长过匹配窗口)—— ` +
                `退 2 就等于把「浏览器在但没连上」又并回「缺依赖」,而名字还在、其余断言全绿`,
        );
    // spawn 失败。**不按「行」找**:逐行 `find` 等于把判据钉在 prettier 的换行决定上 ——
    // 这两行都贴着 printWidth 80 的上限、余量只有几列(具体几列取决于怎么算 CJK 宽度,
    // 别把某个具体数字写死在这里 —— 本卡已经因为「拿 awk 的字符数当 prettier 的显示宽」
    // 把错数写进过 commit;结论不依赖那个数:余量小到一次改名就会被折行),
    // 一旦折成两行,`find` 到的那一行里就没有 `browserFailed`,判据**假红**且报
    // 「没走 browserFailed」,把人指到不存在的问题上。
    // 与下面 `--chrome` 那条同款,改用带上界的跨行匹配。
    if (!/chrome\.on\("error"[\s\S]{0,200}?browserFailed\(/.test(s.code))
        fail(
            `${s.name}:spawn 失败(chrome.on("error"))没走 browserFailed —— ` +
                `能走到 spawn 就说明二进制在,那是失败不是缺依赖`,
        );
    // CDP 握手超时:`if (!targets)` 之后的那一小段里必须调 browserFailed
    const i = s.code.indexOf("if (!targets)");
    if (i < 0) {
        fail(
            `${s.name}:找不到 CDP 握手的 \`if (!targets)\` 分支(判据锚点变了,回来同步本检查)`,
        );
    } else {
        // 窗口同 ③ 段放宽到 2000(剥注释后这一段本就短得多,余量是给将来加代码用的)。
        const seg = s.code.slice(i, i + 2000);
        if (!seg.includes("browserFailed"))
            fail(
                `${s.name}:CDP 握手超时没走 browserFailed(**或该分支长过了 2000 字符的匹配窗口** —— 先确认是哪一种)—— 会静默退回 [SKIP] 且照算 PASS`,
            );
    }
    // 反向:真缺依赖那两处必须**仍然**是 noBrowser(两类不能又被合并回去)。
    // 两个调用点都要断 —— 上一版只断了一个,而 PR 描述里「反向:rc=2 原样」的实跑
    // 在机器上的唯一对应物就是这几条。
    if (!/noBrowser\("本机找不到 Chrome\/Edge"\)/.test(s.code))
        fail(
            `${s.name}:「本机找不到 Chrome/Edge」不再走 noBrowser —— 真缺依赖被误升成失败档`,
        );
    // `\s*` 而不是一个 literal 空格:这一行贴着 printWidth 80 的上限、**余量只有几列**
    //(见上面 spawn 那段:别在注释里写死一个具体列数)—— 任何一次改名都会让 prettier
    // 把它折行,而写死空格的正则会当场**假红**、
    // 还报成「不再走 noBrowser」把人指到不存在的问题上。判据不该钉排版决定。
    if (!/if \(!existsSync\(p\)\)\s*noBrowser\(/.test(s.code))
        fail(
            `${s.name}:\`--chrome\` 路径不存在那处不再走 noBrowser —— 那是真缺依赖,不是「浏览器在但没连上」`,
        );
    // ★ 与上面 browserFailed 那条**同款**:断的是**退出码**,不是名字。
    //   把 `noBrowser()` 退成 3,上面两条与 ②③ 两段全绿,而一台**真没装浏览器**的机器
    //   会在汇总里被写成「浏览器在但没连上」—— 逐字是假话,本卡为两类分家立的那条界线
    //   当场被抹掉。坏的不是判定(两档都不判红),是**摘要说了假话** ——
    //   而「摘要不能说假话」正是本卡的全部主题。
    if (
        !/function\s+noBrowser\s*\([\s\S]{0,900}?process\.exit\(2\)/.test(
            s.code,
        )
    )
        fail(
            `${s.name}:noBrowser() 退的不是 2(或函数体长过匹配窗口)—— ` +
                `退 3 会让「本机没装浏览器」在汇总里显示成「浏览器在但没连上」`,
        );
}

// ---------------------------------------------------------------- ② gates 端
const GATES = path.join(ROOT, "scripts", "gates.ps1");
if (!fs.existsSync(GATES)) fail("找不到 scripts/gates.ps1");
else {
    const ps = stripPsComments(read(GATES));
    if (!/\$rc\s+-eq\s+3\b/.test(ps))
        fail(
            "gates.ps1 Gate 3e 没有 `$rc -eq 3` 分支 —— 浏览器在但没连上会被当成缺依赖",
        );
    if (!/\[FLAKY-SKIP\]/.test(ps))
        fail(
            "gates.ps1 里没有 `[FLAKY-SKIP]` 标记 —— 「没跑成」会和「跳过」长得一样",
        );
    if (!/\$smokeFlaky\s*\+\+/.test(ps))
        fail("`$smokeFlaky++` 不在 —— rc=3 没有独立计数");
    if (!/\$smokeFlaky\s*=\s*0/.test(ps)) fail("`$smokeFlaky` 没有初始化");
    // ★ 本检查的核心:计数要**接进汇总标签**。上面全绿而这条红 = 打了标记却没进摘要。
    //   [SL-318] 一族三条(`$smokeFlaky` / `$draftsAllow` / `$parityWarn`)现在**形态相同**:
    //   `\$<标签>\s*=[^\n]*\$<计数>\b`。两半各修掉一个方向:
    //     · 断的是「**赋值给标签的那一行**里出现了计数」,不是「源码里某处有 `-f $标签, $计数`」——
    //       后者放得过 `Write-Host ('{0}(!{1} 套没跑成)' -f $smokeLabel, $smokeFlaky)`:
    //       计数退回滚屏、`Set-Gate` 拿到的仍是干净的标签、汇总表照写 PASS,而断言照绿,
    //       失败文案却说着「没有被拼进标签」(复审【建议】,三条各配一格删除式);
    //     · 末尾 `\b`:收在词尾的变量名断言,改名成 `…X`(= 拼进标签的是个空变量)会命中前缀
    //       照样绿。同段的 `= 0` 与 `+=` 两类后面还要求一个非词字符,天然没这问题,不动。
    //   **三条一起改**是有意的:第一轮我只升级了 `$parityWarn`,于是「一族三条不留一条没补的」
    //   这句话在同一个 PR 内当场变成假的 —— 复审第 2 轮点的正是这个。
    //   [SL-322] 再收一格:计数要落在 **`-f` 的实参**里,不只是「出现在赋值那一行」。
    //   旧形态 `\$<标签>\s*=[^\n]*\$<计数>\b` 放得过单行的
    //     `if ($smokeFlaky -gt 0) { $smokeLabel = '{0}(…)' -f $smokeLabel }`
    //   —— 计数只在**条件**里被读了一次,真正拼进标签的是个不带计数的串,而断言照绿。
    //   收成:`=` 之后**直接跟一个单引号格式串,再跟 `-f`**,计数出现在其后。三条共用下面
    //   这一个构造器,不是各写各的字面量(一族三条最容易漂的就是「只升级了一条」)。
    //
    //   为什么不能只写「`=` 之后有个 `-f`,计数在它后面」(复审第 1 轮【重要】,实测):
    //   `-f` 是**裸子串**,那只证明「计数在同一行某个 `-f` 之后」。把分支顺序换一下就重新变绿 ——
    //     `$smokeLabel = if ($true) { '{0}(…)' -f $smokeLabel } elseif ($smokeFlaky -gt 0) { … }`
    //   `-f` 在前、计数在后 ⇒ 命中,而标签里一样没有计数。所以要把「RHS 是个条件表达式」
    //   整族挡在门外:要求 `=` 后**直接**是格式串。今天三个用点的 RHS 都以 `'` 开头,零代价。
    //   方向是**假红**(改用双引号或 `($base) -f …` 会红回来读这段),按本文件的不对称原则可接受。
    //
    //   ⚠ **单行边界**:这三条只认**写在一行里**的赋值。放开跨行,`[\s\S]*` 会一路吃过注释
    //   与下一条赋值,把两处不相干的赋值粘成一条命中,判据当场没牙。真要拆行,改这条判据、别删它。
    //   失败文案里点了这一条,免得下一个人照着「没拼进标签」去查一个不存在的问题。
    //   [SL-322 复审第 2 轮] 「单行」这句原来**比判据强半格**:JS 的 `\s` 是**包含 `\n`** 的,
    //   而这条正则里有三处 `\s`(`\s*=\s*`、`'\s*-f`、`-f\s`)—— 断在 `=` 后、`-f` 前、`-f` 后
    //   的三种拆行**照绿**,只有断在格式串内部或断在「`-f` 与计数之间」才红(卡面 ③ 那格用的
    //   正是后者,所以那格的实测结论没错,只是不能推广成「拆行必红」)。两条路都能对齐,
    //   这里选**把判据改真**而不是把话说软:三处换成 `[^\S\n]`(横向空白),注释这句才立得住。
    //   ⚠ 尾部还要排掉 `#`:`ps` 只剥了**整行**注释,行尾注释原样留着,于是
    //     `$smokeLabel = '{0}' -f $smokeLabel   # $smokeFlaky 那一档走上面`
    //   会让尾部吃到注释里的计数名 ⇒ 绿,而标签里依旧没有计数 —— 与本卡①是同一族(散文冒充
    //   判据),只换了个位置,且 gates.ps1 里行尾注释是活写法。格式串在 `-f` 之前,里面的 `#`
    //   不受影响;只有把 `#` 写进**实参**才会假红,零现存用点(复审第 2 轮)。
    //   ⚠ 光收尾部**不够**:格式串那段若写成贪婪的 `'[^\n]*'`,它会一路吃到本行**最后**一个
    //   引号,把 `#` 一并吞下,尾部的 `[^\n#]*` 就落在注释**之后**、什么也拦不到 ——
    //     `$smokeLabel = '{0}' -f $smokeLabel   # 旧版 '{1}' -f $smokeFlaky 已废`
    //   实测在只收了尾部的那一版上**照绿**。所以格式串必须**不跨引号**(`[^'\n]*`)。
    //   两半是一对:后一半防注释、前一半别把注释让进来(复审第 3 轮)。
    //   PowerShell 单引号串里的 `'` 要写成 `''`,那种写法会红回来读这段,方向仍是假红;
    //   今天三个用点的格式串里都没有 `'`,零代价。
    //   ⚠ **行首锚是这一族的收口**(复审第 4 轮)。前几轮一直在收「匹配段里能出现什么」,
    //   而漏的是「匹配可以从**哪里**起头」:没有锚时,引擎在真赋值处对不齐,就挪到**行尾注释里
    //   整句引用的那条赋值**上重新起头,整段命中 ⇒ 绿,而真正赋给标签的是个不带计数的值 ——
    //     `$smokeLabel = $suffixed   # 旧写法:$smokeLabel = '{0}(!{1})' -f $smokeLabel, $smokeFlaky`
    //   实测在只收了引号的那一版上照绿。加 `^` + `m` 之后,**注释里的内容永远不在行首**,
    //   这一整族(不只是这一个写法)一次关掉 —— 前几轮那种「收一处、相邻语法自由度再冒一处」
    //   的叠层到此为止。真赋值本来就顶格(允许缩进),零代价。
    const H = "[^\\S\\n]"; // 横向空白:不含换行的 \s
    const labelTakesCount = (label, count) =>
        new RegExp(
            "^" +
                H +
                "*\\$" +
                label +
                H +
                "*=" +
                H +
                "*'[^'\\n]*'" +
                H +
                "*-f" +
                H +
                "[^\\n#]*\\$" +
                count +
                "\\b",
            "m",
        );
    if (!labelTakesCount("smokeLabel", "smokeFlaky").test(ps))
        fail(
            "`$smokeFlaky` 没有落在 `$smokeLabel = '…' -f …` 的实参里 —— [FLAKY-SKIP] 只会" +
                "出现在滚屏里,而跑完 gates 的人看的是汇总表:这正是 SL-297 要堵的那个洞原样复现。" +
                "(本判据只认**单行**赋值;若你把它拆成了多行,那不是这句文案说的问题,改判据。)",
        );
    // 反向:rc=2 那一档要还在,且自增的仍是 $smokeSkipped(两类不能共用一个计数器)
    if (!/\$rc\s+-eq\s+2\b/.test(ps))
        fail("gates.ps1 丢了 `$rc -eq 2` 分支(真缺依赖那一档)");
    if (!/\$smokeSkipped\s*\+\+/.test(ps))
        fail(
            "`$smokeSkipped++` 不在 —— rc=2 与 rc=3 共用计数器就等于两类又合并了",
        );

    // ---- [SL-315] gate 3i 的 `[ALLOW]` 放行:与上面 3e 那条**同构** -----------------
    // 同一族、同一个失效方向:打了标记、只在滚屏里闪一行,而汇总表照写干净的 PASS ——
    // 于是「有一条烂在注释块里的豁免」与「没有任何豁免」在本地长得一模一样。
    // SL-295 立的规矩是「豁免不显形就等于没有豁免纪律」,那条规矩自己也需要有人守着。
    if (!/\$draftsAllow\s*=\s*0/.test(ps))
        fail("`$draftsAllow` 没有初始化 —— gate 3i 的 ALLOW 放行没有独立计数");
    if (!/\$draftsAllow\s*\+=/.test(ps))
        fail("`$draftsAllow` 没有自增 —— ALLOW 行没有被数进去");
    // ★ 与 3e 那条**同形态**:`\$<标签>\s*=[^\n]*\$<计数>\b`,两半各修掉一个方向。
    //   完整理由写在上面 3e 那条旁边,这里不抄一遍(抄两处就是下一句待漂的注释)。
    //   末尾 `\b` 是本卡删除式第 15 格照出来的:改名成 `$draftsAllowX` 时旧写法命中前缀、照样绿。
    if (!labelTakesCount("parityLabel", "draftsAllow").test(ps))
        fail(
            "`$draftsAllow` 没有落在 `$parityLabel = '…' -f …` 的实参里 —— ALLOW 行只会出现在" +
                "滚屏里,而跑完 gates 的人看的是汇总表:与 SL-297 在 3e 上堵的是同一个洞。" +
                "(本判据只认**单行**赋值,理由与边界见 3e 那条旁边。)",
        );
    // ★ 本卡特有的第二条:计数模式要**对真信号行命中、对成功散文不命中**。
    //   断的是**行为**,不是拼写:从 gates.ps1 里把那条口径**抽出来实跑正反例**。
    //   拼写式断言(「源码里有没有写着这几个字符」)在这一条上是没牙的 ——
    //   两个坏写法都会被它放过一个方向:
    //     · 裸标记      ⇒ 把成功散文里提到的那句也数进去,**0 条也恒报 1**;
    //     · 只写 `^`(不吃前导空格)⇒ 真信号行带两个前导空格,**有也恒报 0**。
    //   两个方向一样坏,而「恒 0」那种连删除式都照不出来(0 == 0)。
    //   PS 与 JS 在 `^ \s * \[ \]` 这几个元字符上同义,可以直接用 JS 引擎代跑。
    //   好处还有一条:不再逐字耦合到某一种写法 —— 谁换成等价实现,只要行为对就不会假红。
    //
    //   [SL-318] gates.ps1 把这条口径收成了**一处定义**($markerCount,`{0}` 占标记名),
    //   **两处计数**(ALLOW / WARN)都从它实例化 —— BASE 只回显、没有计数,不在这一档里
    //   (「三个标记一份判据」那句说的是下面 §④ 的**散文守卫**,别串到计数这一档上)。
    //   所以这里也只读一次、对两个标记各跑一遍夹具:两份逐字相同的字面量的坏处不是重复,
    //   是**只改一份** —— 那时「WARN 收紧了、ALLOW 没有」在汇总表上看不出任何差别。
    //   下面另有两条断言钉住「用点确实走的是它」,否则谁在某一处把字面量写回去,
    //   这里照样绿(读到的还是那份好定义)。
    const fmtM = /\$markerCount\s*=\s*'([^']+)'/.exec(ps);
    if (!fmtM)
        fail(
            "gates.ps1 里读不到 `$markerCount = '<模式>'` —— 两处计数的口径没有一处定义," +
                "也就无法验证它到底数不数得对",
        );
    else {
        // ★ 代跑链上多了一步 **String.Format**,而 `{` `}` 在 String.Format 与正则里**都**有意义,
        //   两边在这一步上**不同义** —— 这条边界不能只写在注释里,写成机器判据(复审【建议】):
        //     `$markerCount = '^\s{0,2}\[{0}\]'` 看着像「把两个前导空格写精确」,实际
        //     PowerShell 把 `{0,2}` 读成「第 0 个参数、右对齐宽 2」⇒ 真正则成了 `^\sWARN\[WARN\]`
        //     ⇒ **有降级也恒报 0**;而这边 `replaceAll("{0}", …)` 找的是字面 `{0}`、`{0,2}` 里没有,
        //     于是夹具拿到的是 `^\s{0,2}\[WARN\]` ⇒ 正例过、反例也过 ⇒ **全绿**。
        //   方向是漏判,且是「恒 0」那一种(下面写着它连删除式都照不出来)。所以:
        //   **这份定义里除 `{0}` 外不得出现花括号**;要写量词就用 `\s\s?` 这类等价形态。
        //   判法:把所有 `{0}` 抠掉,剩下**一个花括号都不许有**(比写一条带前后顾的正则清楚)。
        if (/[{}]/.test(fmtM[1].replaceAll("{0}", "")))
            fail(
                "`$markerCount` 的模式 /" +
                    fmtM[1] +
                    "/ 里除 `{0}` 外还有花括号 —— PowerShell 的 `-f` 会把 `{0,2}` 这类量词当成" +
                    "格式规格(结果是一条永不命中的正则、有降级也恒报 0),而这边的夹具替换找的是" +
                    "字面 `{0}`、照样全绿。要写量词请改用 `\\s\\s?` 这类不带花括号的等价形态。",
            );
        // 正例 / 反例都**按标记拼装**:整串写在源码里会让下面那条「散文里不许出现方括号标记」
        // 的守卫扫到本文件自己,入库即自炸(本仓「扫描器入库才炸」那一族的老判例)。
        const cases = [
            {
                mark: "ALLOW",
                who: "$draftsAllow",
                // 真放行行:check-changelog-drafts.mjs 的 `"  [ALLOW] #"`,两个前导空格。
                good: "  [" + "ALLOW] #189 放行 —— 理由",
                // 成功散文里提了一嘴 —— 用带方括号的写法当反例才有区分度:拿今天那句
                // 不带方括号的成功消息去试,裸标记也不会命中,这一格就没牙了。
                bad: "…放行的号见 [" + "ALLOW] 行;…",
                goodWhy: "有放行也恒报 0",
                badWhy: "0 条放行恒报 1",
            },
            {
                mark: "WARN",
                who: "$parityWarn",
                // 真降级行:check-native-paths / check-bridge-parity 的写法,同样两个前导空格。
                good: "  [" + "WARN] 本机没有 grep,跳过这一档。",
                bad: "① 手写用例全过;另见 [" + "WARN] 那一档…",
                goodWhy: "有降级也恒报 0,而恒 0 连删除式都照不出来",
                badWhy: "没有降级也会在汇总表里报出一档",
            },
        ];
        for (const c of cases) {
            // `replaceAll` 而不是 `replace`:PowerShell 的 `-f` 把 `{0}` **出现几次换几次**,
            // 而 JS 的 `replace(string, …)` **只换第一次** —— 两边在这一步上不同义。
            // 于是 `'^\s*\[{0}\]|\[{0}\]'`(第二个分支是裸匹配 ⇒ 散文照数,正是本卡要堵的洞)
            // 在 PS 上两个分支都实例化、真的漏,而这边只换掉第一个 ⇒ 第二个分支成了永不命中的
            // 字面量 ⇒ 正例过、反例也过 ⇒ **守卫全绿**。方向是漏判(复审【重要】)。
            const src = fmtM[1].replaceAll("{0}", c.mark);
            const re = new RegExp(src);
            if (!re.test(c.good))
                fail(
                    `${c.who} 的计数口径 /${src}/ 数不到真信号行(带两个前导空格)—— ${c.goodWhy}`,
                );
            if (re.test(c.bad))
                fail(
                    `${c.who} 的计数口径 /${src}/ 把成功路径的散文也数进去了 —— ${c.badWhy}`,
                );
        }
    }
    // ★ 一处定义只有在**用点真的走它**时才算数:两处都要按 `$markerCount -f '<标记>'` 实例化。
    //   少了这两条,谁在某一处写回字面量,上面那圈夹具照样全绿(它读的是那份好定义)。
    if (!/\$draftsAllow\s*\+=[^\n]*\$markerCount\s+-f\s+'ALLOW'/.test(ps))
        fail(
            "`$draftsAllow` 的计数没走 `$markerCount -f 'ALLOW'` —— 口径又被抄了一份字面量," +
                "两份就会只改一份",
        );
    if (!/\$warnLines\s*=[^\n]*\$markerCount\s+-f\s+'WARN'/.test(ps))
        fail(
            "`$warnLines` 的匹配没走 `$markerCount -f 'WARN'` —— 口径又被抄了一份字面量," +
                "两份就会只改一份",
        );
    // ★ [SL-322] **两引擎的第三条边:大小写**。前面那圈夹具用 JS 正则代跑 PowerShell 的
    //   模式,靠的是「同一条模式在两个引擎里同义」。量词与转义那两条边前几卡已经钉过,
    //   剩下的这条不在**模式**里、在**运算符**里:PowerShell 的 `-match` 默认不区分大小写,
    //   JS 的 `RegExp.test` 默认区分 —— 于是 `  [warn] …` 会被 gates 数进降级档,而守卫和
    //   它的夹具全都扫不到(实测 `-match` True / `-cmatch` False)。两边各自绿,数对不上。
    //   收法:凡是拿 `$markerCount` 去匹配的地方一律 `-cmatch`;这里**正反两条都钉**——
    //   既要求 `-cmatch` 在,也要求没有任何一处 `-match` 还挂在 `$markerCount` 上
    //   (只钉前者时,再抄一处 `-match ($markerCount …)` 照样绿)。
    for (const c of [
        { who: "$draftsAllow", mark: "ALLOW" },
        { who: "$warnLines", mark: "WARN" },
    ]) {
        const re = new RegExp(
            "-cmatch\\s*\\(\\s*\\$markerCount\\s+-f\\s+'" + c.mark + "'",
        );
        if (!re.test(ps))
            fail(
                c.who +
                    " 的匹配没用 `-cmatch` —— PowerShell 的 `-match` 不区分大小写," +
                    "`[" +
                    c.mark.toLowerCase() +
                    "]` 会被 gates 数进去而守卫扫不到,两边各自绿、数对不上",
            );
    }
    // 第三处用点是 **ALLOW+BASE 的裸回显**,它不走 `$markerCount`(是字面量),所以上面
    // 那圈按标记名生成的断言钉不住它。退回 `-match` 后的形态是「小写标记**回显了、但不计数**」——
    // 滚屏里有一行、汇总表里 0 处,正是这一族一直在堵的「滚屏与汇总分家」。给它一条自己的断言,
    // 别让人以为三处都上了机检(复审第 1 轮)。用 `includes` 不用正则:这串里全是方括号与
    // 反斜杠,正则里再转义一遍只会多一层看不懂的字符。
    const ECHO_ARG = " '\\[ALLOW\\]|\\[BASE\\]'";
    if (!ps.includes("-cmatch" + ECHO_ARG))
        fail(
            "ALLOW+BASE 的回显没用 `-cmatch` —— 小写标记会被回显却不计数," +
                "滚屏里有一行、汇总表里 0 处,正是这一族要堵的「滚屏与汇总分家」",
        );
    // 反向:大小写不敏感的运算符不止 `-match`。PowerShell 里 `-notmatch` / `-replace` /
    // `-split` 默认同样不区分大小写(对应 `-cnotmatch` / `-creplace` / `-csplit`)。今天没有
    // 用点,但 `-notmatch ($markerCount -f 'WARN')`(反过来滤掉标记行)是很自然的下一个写法,
    // 会**同时**绕过上面的正条与这条反条 —— 那这条边就白收了(复审第 1 轮)。
    // `-cmatch` / `-cnotmatch` / `-creplace` / `-csplit` 不会被误伤:`-` 后面接 `c` 时对不齐。
    // [SL-322 复审第 2 轮] 同一条推理反过来说明 **`-i…` 一族整族漏着**:PowerShell 的显式
    // 不敏感形态是 `-imatch` / `-inotmatch` / `-ireplace` / `-isplit`,而写下那个 `i` 的人是
    // **明确**要不区分大小写 —— 正是这条边禁止的语义,比 `-notmatch` 更该挡。`Select-String`
    // 也一并收:它默认同样不敏感(要 `-CaseSensitive` 才敏感),且**不是假想形态** ——
    // gate 3g 那处纯回显就是 `Select-String -Pattern '\[WARN\]'`(不计数,本卡有意不动它),
    // 说明这个写法在本文件里是活的,哪天有人把计数改写成它,这条边就白收了。
    const CI_OPS =
        /-i?(?:not)?match\s*\(\s*\$markerCount|-i?(?:replace|split)\s*\(\s*\$markerCount|Select-String[^\n]*-Pattern\s*\(\s*\$markerCount/;
    if (
        CI_OPS.test(ps) ||
        ps.includes("-match" + ECHO_ARG) ||
        ps.includes("-notmatch" + ECHO_ARG) ||
        ps.includes("-imatch" + ECHO_ARG) ||
        ps.includes("-inotmatch" + ECHO_ARG)
    )
        fail(
            "还有一处拿大小写不敏感的运算符匹配标记(`-match` / `-notmatch` / `-replace` / " +
                "`-split` / 它们的 `-i…` 显式形态 / `Select-String -Pattern`)—— 标记一律走 " +
                "`-c…` 形态,留一处不区分大小写就等于这条边没收",
        );

    // ---- [SL-318] gate 3i 的 WARN 降级计数:与上面 ALLOW 那条**同构**,风险高一档 ----
    // 同构在两层:行为上都是「脚本成功路径打出来的标记行 → 数出来 → 拼进汇总标签」;
    // 写法上三条断言**同一个形态** `$<标签>\s*=[^\n]*$<计数>\b` —— 别只对其中一条做升级
    // (复审第 2 轮点的正是这个:第 1 轮我只升级了这一条,那句「一族三条不留一条没补的」
    // 在同一个 PR 内当场变成假的)。
    // 高一档在:ALLOW 的裸匹配只多回显一行,而 WARN 的那个数**直接就是汇总表里的降级档数** ——
    // 任一脚本在成功散文里提一句带方括号的 WARN,汇总表当场多报一档降级,而 gates.ps1 自己
    // 写着「喊错一次,下次真降级也会被当噪声」。所以这一族的计数要一份判据、一个口径。
    if (!/\$parityWarn\s*=\s*0/.test(ps))
        fail("`$parityWarn` 没有初始化 —— gate 3i 的 WARN 降级没有独立计数");
    if (!/\$parityWarn\s*\+=/.test(ps))
        fail("`$parityWarn` 没有自增 —— 降级行没有被数进去");
    // ★ 与 3e / ALLOW 两条同一个核心:计数要**接进汇总标签**。
    //   断的是「**赋值给 $parityLabel 的那一行里出现了 $parityWarn**」,不是「源码里某处有
    //   `-f $parityWarn`」(复审【建议】,两个方向各有代价,第一版两头都占):
    //     · **弱**:写成 `Write-Host ('降级 {0} 处' -f $parityWarn)` 而不写回标签 —— 计数退回
    //       滚屏、汇总表照写干净的 PASS,而这条断言按旧写法**照绿**,失败文案却说着「没拼进标签」;
    //     · **假红**:哪天有人把这两行规范成同一形态(`$parityLabel = '{0}…{1}…' -f $parityLabel,
    //       $parityWarn`,一个很自然的整理),`-f` 后面跟的就成了 `$parityLabel`,旧写法当场假红
    //       而行为完全正确。现在这条对两种形态都命中,且真的钉住了「落进标签」。
    if (!labelTakesCount("parityLabel", "parityWarn").test(ps))
        fail(
            "`$parityWarn` 没有落在 `$parityLabel = '…' -f …` 的实参里 —— 降级只会出现在滚屏里," +
                "而跑完 gates 的人看的是汇总表:与 SL-297 在 3e 上堵的是同一个洞。" +
                "(本判据只认**单行**赋值,理由与边界见 3e 那条旁边。)",
        );
    // 计数口径的正反例夹具与「用点走的是一处定义」两条断言,都在上面 ALLOW 那圈里
    // 按标记跑了一遍 —— 两处计数一份判据,不在这里再抄一份。

    // ★ 第三条:**成功路径打出来的话里不许出现方括号标记**。gate 3i 对这一圈脚本的
    //   成功输出按裸标记回显 ALLOW 与 BASE,又按行首标记把 WARN 数进汇总标签 —— 所以任何
    //   一句「见 ALLOW 行」这样**带方括号**的散文都会冒充一条真信号:轻则回显多一行,
    //   重则(那句散文恰好落在行首那一档)汇总表当场多报一档降级。
    //   这条不变量到 [SL-315] 为止已被违反**三次**(#197 第 5 轮那次是 BASE、`379de23`
    //   那次是 ALLOW、以及本卡第一版**在本文件自己身上**),三次都只有散文守着 ——
    //   所以给它一个跨文件的执行者,而不是每个脚本各写一份手抄自测。
    //   **判据的第 ④ 版**:扫的是「剥掉整行注释后的整份源码」,既不切字符串、也不看
    //   `console.log(...)` 的实参;逐个标记往回跳过空白,**前一个字符是引号**才算真信号。
    //   前三版怎么错的、这版的已知边界在哪,写在**头注的边界表**里(§④ 那一节),
    //   别只读这里 —— 那张表才是这道守卫的口径真源。
    //   [SL-318] 允许的引号是 `"` 与 `'` **两种**,反引号**不在其中**:markdown 反引号
    //   正是本仓散文引用一个标记的惯例(这个文件的注释里就有一堆),把它留在允许集里
    //   等于给整类散文盖章 —— 前三版是**扫不到**那类写法,第 ④ 版扫到了却**放行**,
    //   比扫不到更坏。反向代价为零:今天七个脚本里的真信号**全部**是双引号起头的
    //   `"  [标记] …"`,没有一处用模板串起头(**不写「几处」**,理由见头注 §④)。
    //   清单**从 gates.ps1 的 foreach 里读出来**,不手抄 —— 手抄的话新加一个脚本就漏守,
    //   而这正是本仓「照模板复制一份就漏掉」那一族的形态。
    const listM = /foreach\s*\(\s*\$sc\s+in\s+@\(([^)]*)\)\s*\)/.exec(ps);
    const gate3iScripts = listM
        ? [...listM[1].matchAll(/'([^']+\.mjs)'/g)].map((m) => m[1])
        : [];
    if (gate3iScripts.length === 0)
        fail(
            "从 gates.ps1 的 gate 3i `foreach` 里读不出脚本清单 —— " +
                "下面那条「成功消息不许带方括号标记」会退化成永远通过",
        );
    for (const sc of gate3iScripts) {
        const f = path.join(ROOT, "scripts", sc);
        if (!fs.existsSync(f)) {
            fail(`gate 3i 的清单里有 ${sc},但 scripts/ 下找不到它`);
            continue;
        }
        const src = stripJsComments(read(f));
        // 判据本身与它的边界都在头注 §④,这里只留「读代码时会想问的那一句」。
        // 三个标记**同一份判据**([SL-318]):gate 3i 对 ALLOW / BASE / WARN 的处理各不相同
        // (前两个只回显,WARN 还要计数进标签),但「散文冒充信号」这个失效方向完全一样。
        for (const m0 of src.matchAll(/\[(?:ALLOW|BASE|WARN)\]/g)) {
            const before = src.slice(0, m0.index).replace(/[ \t]+$/, "");
            // 允许集**只有两种引号**,反引号不在内(理由见上面 [SL-318] 那段与头注 §④)。
            if (/["']$/.test(before)) continue; // 开头即标记 = 真信号
            fail(
                `${sc}:源码里有一句散文提到了方括号标记` +
                    `(「${src.slice(Math.max(0, m0.index - 12), m0.index + 9).replace(/\n/g, " ")}」)—— ` +
                    `gate 3i 按标记回显/计数成功输出,这句会冒充一条真信号;` +
                    `提到 ALLOW / BASE / WARN 时去掉方括号(要写成真信号,就让它紧跟在 " 或 ' 后面开一条字符串)`,
            );
        }
    }
}

// ---------------------------------------------------------------- ③ CI 端
const WF = path.join(ROOT, ".github", "workflows", "format.yml");
if (!fs.existsSync(WF)) fail("找不到 .github/workflows/format.yml");
else {
    // 与 ② 段**对称**地先剥掉整行注释(复审指出:不剥的话,rc=3 分支里一行
    // `# … ::warning …` 注释就能顶替真 `echo`,那是**漏判**)。YAML/bash 的整行注释同为 `#`。
    const yml = read(WF)
        .split("\n")
        .filter((l) => !/^\s*#/.test(l))
        .join("\n");
    // 窗口取 2000 而不是 600:rc=3 分支当前约 330 字符,而**这类分支最容易长大的正是中文注释**;
    // 超窗时 `m` 为 null,报出来的却是「没有 rc=3 分支」—— 那个分支明明在,会把人指到一个
    // 不存在的问题上。所以既放宽窗口,也在失败文案里点明「或超出匹配窗口」这一可能。
    const m =
        /elif\s+\[\s*\$rc\s+-eq\s+3\s*\]\s*;\s*then([\s\S]{0,2000}?)(?:elif|fi)\b/.exec(
            yml,
        );
    if (!m)
        fail(
            "format.yml 的 web-smoke 没有 `elif [ $rc -eq 3 ]` 分支(**或该分支长过了 2000 字符的匹配窗口** —— 先确认是哪一种)—— rc=3 会落进 " +
                "`[ $rc -ne 0 ]` ⇒ ::error:: + fail=1,在 required check 上把瞬时抖动变成硬红",
        );
    else {
        if (!/::warning/.test(m[1]))
            fail(
                "format.yml 的 rc=3 分支没有 ::warning:: —— 降级在 checks 摘要里看不见",
            );
        if (/::error/.test(m[1]) || /fail=1/.test(m[1]))
            fail(
                "format.yml 的 rc=3 分支判红了(::error 或 fail=1)—— 与本卡「不判红」的决定相反;" +
                    "要改成判红须先有重试/退避(SL-297 第二步),并同步 gates 侧与本检查",
            );
    }
}

// ---------------------------------------------------------------- §⑤ 摘录对拍
// [SL-327] `[BASE]` 那一行的格式在**三个地方**写着:`check-changelog-drafts.mjs` 里**真正的
// 拼装**(唯一真源),以及两处**手抄摘录** —— 该文件头注 §边界、`gates.ps1` gate 3i 的回显那段。
// SL-319 改了输出格式,两处摘录当轮都没跟上,直到 SL-326 才回扫补上 —— **同一个洞修了两次,
// 机器一次都没醒**。它比别的漂移更钝:不同源时**什么都不会发生**,只在有人照着摘录去核输出时
// 才害人,那正是「基线与判据不同源比没有基线更坏」那句话的形态(#210 复审【建议】)。
//
// 判据:从真拼装里抠出**字面片段**(`+` 之间那些字符串常量),要求两处摘录都逐字含着它们。
// 钉片段而不是钉整行:摘录里的 `<base>` / `N` / `K` 是占位符,与运行时的变量对不上,
// 整行比对只会得到一条永远红的判据。
const DRAFTS = path.join(ROOT, "scripts", "check-changelog-drafts.mjs");
if (!fs.existsSync(DRAFTS)) fail("找不到 scripts/check-changelog-drafts.mjs");
else {
    const src = read(DRAFTS);
    // 真拼装:`"  [BASE] " + base + "@" + … + " 条提交标题(落地位 " + …` ——
    // 取那一段里所有双引号字面量,留下**有汉字或标点**的那些(纯符号的 `@` 之类不具区分度)。
    const asm = /"\s*\[BASE\][\s\S]{0,2000}?个待合并的号"/.exec(src);
    if (!asm)
        fail(
            "check-changelog-drafts.mjs 里找不到 [" +
                "BASE] 那行的拼装 —— 要么判据锚点变了,**要么这段拼装长过了匹配窗口**" +
                "(中间插了长注释?),先确认是哪一种再回来同步本段",
        );
    else {
        const frags = [...asm[0].matchAll(/"([^"]*)"/g)]
            .map((m) => m[1])
            .filter((t) => /[一-鿿]/.test(t));
        if (frags.length === 0)
            fail(
                "从 [" +
                    "BASE] 拼装里抠不出任何带汉字的字面片段 —— 这一格会退化成永远通过",
            );
        // ⚠ 头注那份摘录**只能拿头注去比**:它与真拼装同在一个文件里,拿整份文件比的话,
        //    片段总能在真拼装那一行找到 ⇒ 摘录被改坏了也照绿(实测过:那样注入时本段无牙)。
        //    头注到 `import` 为止,切在那里最稳。
        // 切点找不到时**判负**,不能落到 `slice(0, -1)`(= 整份文件少一个字符)——
        // 那样片段总能在真拼装那行找到,这一格无声退化成永远绿(与下面 frags 为空同族)。
        // `import fs` 只是那个文件的实现细节:合并 import、改成 `import * as fs` 都会让
        // 切点消失,而那时**没有任何红**告诉你判据已经没了(复审【重要】)。
        const headEnd = src.indexOf("import fs");
        if (headEnd <= 0)
            fail(
                "check-changelog-drafts.mjs 里找不到头注的切点 `import fs` —— 摘录对拍无从下手,故 fail-closed(落到整份文件比的话这一格会永远绿)",
            );
        // 切点没了就**跳过**这条 excerpt:上面那条 fail 已经是真因,再把 `""` 喂进去会让
        // 四个片段各报一条「摘录与真拼装对不上」,而摘录一个字都没坏 —— 1 条真因 + 4 条
        // 假因,假因还教人去回扫摘录。与下面 gates.ps1 不在时跳过是同一条(复审【建议】)。
        // `<= 0` 而不是 `< 0`:`headEnd === 0` 时切出来是空串,同样落到那 4 条假因上。
        const headNote = headEnd > 0 ? src.slice(0, headEnd) : null;
        const excerpts = [
            ...(headNote !== null
                ? [["check-changelog-drafts.mjs 头注 §边界", headNote]]
                : []),
            // gates.ps1 不在的话**跳过**这条:§② 已经报过真因,这里再报四条「对不上」
            // 只会把人指到假因上(复审【建议】,与本卡在修的「第二次红指错方向」同族)。
            ...(fs.existsSync(GATES)
                ? [["gates.ps1 gate 3i 的回显那段", read(GATES)]]
                : []),
        ];
        // 摘录是**会换行的散文**:头注那份就断在 `);` 与「块里」之间,而真拼装里它们相连。
        // 所以两边都**去掉所有空白**再比 —— 代价是不再钉空格与缩进(那本来也不该由这道判据管),
        // 换来的是「换个地方折行」不会假红。汉字片段本身仍然足够有区分度。
        // 先剥掉行首的注释符(`//` 与 `#`)再去空白 —— 不剥的话折行处会挤出 `);//块里`
        // 这种伪片段,判据当场假红(实测到过)。
        const squeeze = (t) =>
            t.replace(/^[ \t]*(?:\/\/|#)[ \t]?/gm, "").replace(/\s+/g, "");
        for (const [where, text] of excerpts)
            for (const f of frags)
                if (!squeeze(text).includes(squeeze(f)))
                    fail(
                        where +
                            " 的 [" +
                            "BASE] 摘录与真拼装对不上:缺片段「" +
                            f.trim() +
                            "」—— 摘录是手抄的第二份真源,改了输出格式就要回扫它(SL-319 漏过一轮,SL-326 才补)",
                    );
    }
}

